import React, { useState } from 'react';
import {
  FileText,
  Download,
  Copy,
  Check,
  Trash2,
  Share2,
  BookOpen,
} from 'lucide-react';

export default function ReportPanel({
  reportEntries = [],
  onClearReport,
  onRemoveEntry,
  selectedModel,
}) {
  const [copied, setCopied] = useState(false);

  const fullReportMarkdown = [
    `# AgentFlow AI - Executive Research Report`,
    `Generated by: AgentFlow AI (Model: ${selectedModel || 'qwen3:latest'})`,
    `Date: ${new Date().toLocaleDateString()} ${new Date().toLocaleTimeString()}`,
    `---`,
    `\n## Synthesized Research Findings\n`,
    ...reportEntries.map(
      (entry, idx) =>
        `### Finding ${idx + 1} (${entry.sourceModel || 'Ollama'})\n*Recorded: ${entry.timestamp}*\n\n${entry.content}\n`
    ),
    `\n---\n*Verified with AgentFlow AI Research Pipeline*`,
  ].join('\n\n');

  const handleCopyReport = () => {
    navigator.clipboard.writeText(fullReportMarkdown);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadReport = () => {
    const blob = new Blob([fullReportMarkdown], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `agentflow-research-report-${Date.now()}.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="report-panel-card">
      <div className="report-header-row">
        <div className="report-title-group">
          <FileText size={18} className="report-title-icon" />
          <div>
            <h2 className="report-title">Synthesized Research Report</h2>
            <span className="report-count-tag">
              {reportEntries.length} {reportEntries.length === 1 ? 'Finding' : 'Findings'} Compiled
            </span>
          </div>
        </div>

        {reportEntries.length > 0 && (
          <div className="report-action-buttons">
            <button
              className="report-btn"
              onClick={handleCopyReport}
              title="Copy entire report as Markdown"
            >
              {copied ? (
                <>
                  <Check size={14} className="text-emerald" />
                  <span>Copied</span>
                </>
              ) : (
                <>
                  <Copy size={14} />
                  <span>Copy Markdown</span>
                </>
              )}
            </button>

            <button
              className="report-btn"
              onClick={handleDownloadReport}
              title="Download report as .md file"
            >
              <Download size={14} />
              <span>Download .md</span>
            </button>

            <button
              className="report-btn btn-danger"
              onClick={onClearReport}
              title="Clear all report findings"
            >
              <Trash2 size={14} />
            </button>
          </div>
        )}
      </div>

      <div className="report-body">
        {reportEntries.length === 0 ? (
          <div className="empty-report-state">
            <div className="empty-report-icon-box">
              <BookOpen size={32} className="empty-book-icon" />
            </div>
            <h3 className="empty-report-title">No Report Findings Yet</h3>
            <p className="empty-report-desc">
              When reviewing research inquiries in the chat, click <strong>"Add to Report"</strong> on any response to synthesize it into this executive report dossier.
            </p>
          </div>
        ) : (
          <div className="report-entries-list">
            <div className="report-dossier-header">
              <h3 className="dossier-heading">Executive Research Dossier</h3>
              <p className="dossier-subheading">
                Compiled from autonomous research inquiries and model synthesis.
              </p>
            </div>

            {reportEntries.map((entry, index) => (
              <div key={entry.id || index} className="report-entry-card">
                <div className="entry-header">
                  <div className="entry-title-row">
                    <span className="entry-number">§{index + 1}</span>
                    <span className="entry-source-tag font-mono">
                      {entry.sourceModel || selectedModel}
                    </span>
                    <span className="entry-time">{entry.timestamp}</span>
                  </div>
                  {onRemoveEntry && (
                    <button
                      className="entry-remove-btn"
                      onClick={() => onRemoveEntry(entry.id)}
                      title="Remove from report"
                    >
                      <Trash2 size={13} />
                    </button>
                  )}
                </div>

                <div className="entry-content">
                  {entry.content.split('\n\n').map((para, pIdx) => (
                    <p key={pIdx}>{para}</p>
                  ))}
                </div>
              </div>
            ))}
          </div>
        )}
      </div>
    </div>
  );
}
